// Generates src/font-data.ts from the TTF files in fonts/.
// The driver runs in a worker with no access to repository files, so the fonts ship inside the bundle.
// Run with: npm run fonts

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
// weight is a CSS font-weight value or range, matched by the canvas font stack.
const faces = [
    { family: "Sour Gummy", file: "SourGummy-Medium.ttf", weight: "500" },
    { family: "Sour Gummy", file: "SourGummy-SemiBold.ttf", weight: "600" },
    { family: "Sour Gummy", file: "SourGummy-Bold.ttf", weight: "700" },
    // Thai fallback: Sour Gummy 500 and heavier map to Mitr Medium, lighter weights to Mitr Regular.
    { family: "Mitr", file: "Mitr/Mitr-Regular.ttf", weight: "100 499" },
    { family: "Mitr", file: "Mitr/Mitr-Medium.ttf", weight: "500 900" },
];

const LINE = 100;
const entries = faces.map(({ family, file, weight }) => {
    const base64 = readFileSync(join(root, "fonts", file)).toString("base64");
    const lines = [];
    for (let i = 0; i < base64.length; i += LINE) lines.push(`        "${base64.slice(i, i + LINE)}"`);
    // A flat array keeps the parse tree shallow; a long "a" + "b" chain overflows bundler stacks.
    return `    {\n        family: "${family}",\n        file: "${file}",\n        weight: "${weight}",\n        base64: [\n${lines.join(",\n")},\n        ].join(""),\n    },`;
});

const source = `// Generated by scripts/embed-fonts.mjs from fonts/. Do not edit by hand.
// Sour Gummy and Mitr are licensed under the SIL Open Font License 1.1, see fonts/OFL.txt and fonts/Mitr/OFL.txt.

export const FONT_FACES: { family: string; file: string; weight: string; base64: string }[] = [
${entries.join("\n")}
];
`;
writeFileSync(join(root, "src", "font-data.ts"), source);
console.log(`wrote src/font-data.ts (${source.length} bytes)`);
